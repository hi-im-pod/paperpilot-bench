def col(name, typ, setting, unit=None, allowed=None):
    c = {"name": name, "type": typ, "setting": setting}
    if unit:
        c["unit"] = unit
    if allowed:
        c["allowed"] = allowed
    return c


def q(pid, pattern):
    s = lab.raw_find(pid, pattern)
    if not s or not lab.check_quote(pid, s):
        raise SystemExit(f"quote not found or not matching in {pid}: {pattern}")
    return s.strip()


def cell(value, pid=None, pattern=None, note=""):
    return {"value": value, "quote": q(pid, pattern) if pattern else "", "section": "", "note": note}


