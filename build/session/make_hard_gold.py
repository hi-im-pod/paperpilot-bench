def main():
    rng = random.Random(20261110)
    pre = {"find_papers": "hfp", "comparison_table": "hct", "citation_links": "hcl", "grounded_claims": "hgc", "followup_questions": "hfu"}
    ids = {}
    for typ, p in pre.items():
        keys = [k for k, t, *_ in ITEMS if t == typ]
        nums = list(range(1, len(keys) + 1))
        rng.shuffle(nums)
        ids.update({k: f"{p}-{n:02d}" for k, n in zip(keys, nums)})
    rows = []
    for k, t, s, trap, inp in ITEMS:
        if k == "cl:pi-defenses":
            inp = {"paper_ids": CITATION_SET}
        rows.append({"id": ids[k], "type": t, "split": s, "trap": trap, "input": inp})
    rows.sort(key=lambda r: r["id"])
    (REPO / "tasks" / "hard").mkdir(parents=True, exist_ok=True)
    (REPO / "tasks" / "hard" / "items.jsonl").write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    (Path(__file__).parent / "hard_item_keys.json").write_text(json.dumps(ids, indent=1), encoding="utf-8")
    item = {r["id"]: r for r in rows}

    DRAFTS.mkdir(parents=True, exist_ok=True)
    for old in DRAFTS.glob("*.json"):
        old.unlink()

    def write(key, body):
        it = item[ids[key]]
        d = {"id": it["id"], "type": it["type"], "input": it["input"], **body, **PROV}
        (DRAFTS / f"{it['id']}.json").write_text(json.dumps(d, indent=2, ensure_ascii=False), encoding="utf-8")

    for key, (two, one) in FP.items():
        pool = lab.pool(item[ids[key]]["input"]["topic"], 12)
        for pid in two | one:
            pool.setdefault(pid, ["added by verifier"])
        grades = sorted(({"paper_id": pid, "title": lab.title(pid), "grade": 2 if pid in two else 1 if pid in one else 0,
                          "evidence": "", "found_by": src} for pid, src in pool.items()), key=lambda g: -g["grade"])
        write(key, {"grades": grades})
    for key, rows_ in CT.items():
        write(key, {"rows": rows_, "rows_were_searched": False})
    edges = []
    for a in CITATION_SET:
        for b in CITATION_SET:
            if a != b:
                ok, ev = cites(a, b, lab.PAPERS)
                if ok:
                    edges.append({"citing": a, "cited": b, "in_s2": False, "in_reference_list": True,
                                  "reference_evidence": ev, "needs_review": False, "keep": True})
    write("cl:pi-defenses", {"edges": edges})
    for key, sup in GC.items():
        write(key, {"supporting": [{"paper_id": pid, "quote": q(pid, pat), "why": why} for pid, pat, why in sup],
                    "draft_answer": GC_ANSWER[key]})
    write("fu:co-evolution", {"gaps": [{"paper_id": pid, "quote": q(pid, pat)} for pid, pat in FU_GAPS], "gap_notes": FU_NOTES})
    print(f"wrote {len(rows)} hard items and {len(list(DRAFTS.glob('*.json')))} drafts; citation edges: {[(e['citing'], e['cited'], e['reference_evidence']) for e in edges]}")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
